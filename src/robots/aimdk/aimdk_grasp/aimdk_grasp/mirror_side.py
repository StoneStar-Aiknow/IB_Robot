"""Generate the right arm's planning configuration by mirroring the left arm's.

``config/x2_ultra`` was fitted for the left arm and the left OmniHand. The right
arm's planning model mirrors that hand onto the right wrist
(:func:`aimdk_grasp.planning_model._mirror_hand`), so its configuration follows
mechanically:

* hand spheres are reflected in their link frames by the same reflection as the
  link (``x`` for ``R_palm``, ``y`` for the fingers); body spheres stay, since
  every body link has its own entry already;
* the left arm becomes locked and the right arm planned, its default position
  the mirror of the left one (:data:`aimdk_grasp.joints.ARM_MIRROR_SIGNS`);
* hand-to-wrist exclusions move to the right wrist; body pairs are symmetric;
* the hand cover keeps its certificates (the mirror is an isometry of mesh and
  spheres alike) and records the mirrored placement of the same meshes.

``torso_collision_cover.json`` is copied. ``leg_obstacle.json`` carries the
pelvis and the right leg (``leg_obstacle.build_leg_obstacle(side="right")``).
``arm_gravity.json`` takes the right
arm's chain from the official description and keeps the left fit's kp, torso
tilt (a property of the standing robot, not of an arm) and wrist payload (in
the wrist frame's y = 0 plane, so its own mirror image). Nothing here is fitted or measured;
``test_mirror_side`` checks that the committed directory is what this produces.

Usage: ``mirror_x2_side_config <source config/x2_ultra> <target config/x2_ultra_right>``.
"""

from __future__ import annotations

import copy
import json
import shutil
import sys
from pathlib import Path

import numpy as np
import yaml

from aimdk_grasp.joints import ARM_MIRROR_SIGNS, LEFT_ARM, RIGHT_ARM, swap_side_name

#: Files of a side's planning configuration; arm_gravity and leg_obstacle are not planning files.
PLANNING_FILES = (
    "robot.yml",
    "hand_collision_cover.json",
    "hand_collision_reference.json",
    "torso_collision_cover.json",
)
#: The arm gravity model (aimdk_grasp.arm_gravity), generated beside the planning files.
GRAVITY_FILE = "arm_gravity.json"
#: The fine check's fixed leg obstacle (aimdk_grasp.leg_obstacle).
LEG_FILE = "leg_obstacle.json"
HEADER = """\
# GENERATED by aimdk_grasp.mirror_side from config/x2_ultra/robot.yml: do not edit.
# cuRobo robot configuration of the X2 Ultra right arm with the right OmniHand, the
# mirror image of the left arm's configuration (see aimdk_grasp.mirror_side).
"""


def _reflection(link: str) -> np.ndarray:
    return np.diag([-1.0, 1.0, 1.0]) if link == "R_palm" else np.diag([1.0, -1.0, 1.0])


def mirror_spheres(link: str, spheres: list[dict]) -> list[dict]:
    """``link``'s spheres as the right hand's, or unchanged for a body link."""
    if not link.startswith("R_"):
        return copy.deepcopy(spheres)
    reflection = _reflection(link)
    return [
        {
            **sphere,
            "center": [float(value) + 0.0 for value in reflection @ np.asarray(sphere["center"], dtype=float)],
        }
        for sphere in spheres
    ]


def _mirror_pair(a: str, b: str) -> tuple[str, str]:
    """Hand pairs move to the right wrist; a body pair is its own mirror (checked)."""
    if a.startswith("R_") or b.startswith("R_"):
        return swap_side_name(a), swap_side_name(b)
    return a, b


def mirror_robot_config(config: dict) -> dict:
    config = copy.deepcopy(config)
    if (config["planning_model"] or {}).get("side", "left") != "left":
        raise ValueError("source configuration is not the left arm's")
    config["planning_model"]["side"] = "right"
    kin = config["robot_cfg"]["kinematics"]
    kin["collision_spheres"] = {
        link: mirror_spheres(link, spheres) for link, spheres in kin["collision_spheres"].items()
    }
    pairs = {tuple(sorted((a, b))) for a, others in kin["self_collision_ignore"].items() for b in others}
    body = {pair for pair in pairs if not any(name.startswith("R_") for name in pair)}
    if {tuple(sorted(map(swap_side_name, pair))) for pair in body} != body:
        raise ValueError("body self-collision exclusions are not left/right symmetric")
    ignore: dict[str, list[str]] = {}
    for a, others in kin["self_collision_ignore"].items():
        for b in others:
            x, y = _mirror_pair(a, b)
            ignore.setdefault(x, []).append(y)
    kin["self_collision_ignore"] = ignore
    locks = {}
    for name, value in kin["lock_joints"].items():
        if name in RIGHT_ARM:
            index = RIGHT_ARM.index(name)
            locks[LEFT_ARM[index]] = float(ARM_MIRROR_SIGNS[index] * value) + 0.0
        else:
            locks[name] = value
    kin["lock_joints"] = locks
    cspace = kin["cspace"]
    if list(cspace["joint_names"]) != list(LEFT_ARM):
        raise ValueError("source configuration does not plan the left arm")
    cspace["joint_names"] = list(RIGHT_ARM)
    cspace["default_joint_position"] = [
        float(sign * value) + 0.0
        for sign, value in zip(ARM_MIRROR_SIGNS, cspace["default_joint_position"], strict=True)
    ]
    return config


def mirror_hand_cover(cover: dict, right_model) -> dict:
    """The left hand cover as the right hand's: mirrored spheres, mirrored placement of the same meshes."""
    from aimdk_grasp.robot_model import _sphere_digest

    cover = copy.deepcopy(cover)
    for link, item in cover["links"].items():
        item["spheres"] = mirror_spheres(link, item["spheres"])
        visuals = right_model.findall(f"link[@name='{link}']/visual")
        if len(visuals) != 1:
            raise ValueError(f"{link}: expected one visual in the right model")
        origin, mesh = visuals[0].find("origin"), visuals[0].find("geometry/mesh")
        if Path(mesh.get("filename")).name != Path(item["official_mesh"]["path"]).name:
            raise ValueError(f"{link}: the right model does not reflect the covered mesh")
        item["official_mesh"]["origin"] = dict(origin.attrib)
        item["official_mesh"]["scale"] = mesh.get("scale")
    cover["collision_spheres_sha256"] = _sphere_digest({link: item["spheres"] for link, item in cover["links"].items()})
    cover["mirrored_from"] = "config/x2_ultra/hand_collision_cover.json by aimdk_grasp.mirror_side"
    return cover


def mirror_reference(reference: dict, mirrored_spheres: dict) -> dict:
    from aimdk_grasp.robot_model import _sphere_digest

    reference = copy.deepcopy(reference)
    reference["pairs"] = [list(_mirror_pair(a, b)) for a, b in reference["pairs"]]
    reference["collision_spheres_sha256"] = _sphere_digest(mirrored_spheres)
    reference["scope"] = reference["scope"].replace("left-wrist", "right-wrist") + " (mirrored from the left arm's)"
    return reference


def generate(source: Path) -> dict[str, object]:
    """The right arm's planning files from the left arm's ``source`` directory, by file name."""
    from aimdk_grasp.planning_model import build_planning_model
    from aimdk_grasp.robot_model import planning_model_options

    source = Path(source)
    left = yaml.safe_load((source / "robot.yml").read_text(encoding="utf-8"))
    right = mirror_robot_config(left)
    model = build_planning_model(**planning_model_options(right["planning_model"])).getroot()
    read = lambda name: json.loads((source / name).read_text(encoding="utf-8"))  # noqa: E731
    return {
        "robot.yml": right,
        "hand_collision_cover.json": mirror_hand_cover(read("hand_collision_cover.json"), model),
        # The reference digest is over the robot.yml spheres before the cover replaces any.
        "hand_collision_reference.json": mirror_reference(
            read("hand_collision_reference.json"), right["robot_cfg"]["kinematics"]["collision_spheres"]
        ),
        "torso_collision_cover.json": read("torso_collision_cover.json"),
        GRAVITY_FILE: mirror_arm_gravity(read(GRAVITY_FILE), right["planning_model"].get("description")),
        LEG_FILE: _right_leg(right["planning_model"].get("description")),
    }


def _right_leg(description: str | None) -> dict:
    from aimdk_grasp.leg_obstacle import build_leg_obstacle
    from aimdk_grasp.planning_model import description_share

    return build_leg_obstacle(Path(description) if description else description_share(), "right")


def mirror_arm_gravity(left: dict, description: str | None = None) -> dict:
    """The right arm's gravity model: the official right chain with the left fit's parameters."""
    import xml.etree.ElementTree as ET

    from aimdk_grasp.planning_model import BODY_URDF, description_share

    if [link["joint"] for link in left["chain"]] != list(LEFT_ARM):
        raise ValueError("the left gravity model must chain the seven left arm joints")
    if any(abs(value) > 1e-12 for value in left["payload_offset_m"][1:2]):
        raise ValueError("a wrist payload off the wrist frame's y = 0 plane has no mirror-free right twin")
    robot = ET.parse((Path(description) if description else description_share()) / BODY_URDF).getroot()

    def vector(element, attribute):
        return [float(value) for value in element.get(attribute).split()]

    chain = []
    for name in RIGHT_ARM:
        joint = robot.find(f"joint[@name='{name}']")
        inertial = robot.find(f"link[@name='{joint.find('child').get('link')}']/inertial")
        chain.append(
            dict(
                joint=name,
                xyz=vector(joint.find("origin"), "xyz"),
                rpy=vector(joint.find("origin"), "rpy"),
                axis=vector(joint.find("axis"), "xyz"),
                mass=float(inertial.find("mass").get("value")),
                centre=vector(inertial.find("origin"), "xyz"),
            )
        )
    right = copy.deepcopy(left)
    right["description"] = left["description"].replace("Left-arm", "Right-arm", 1)
    right["chain"] = chain
    right["source"] = dict(left["source"], mirrored_from="config/x2_ultra/arm_gravity.json")
    return right


def write(files: dict[str, object], target: Path) -> None:
    target = Path(target)
    target.mkdir(parents=True, exist_ok=True)
    for name, content in files.items():
        if name.endswith(".yml"):
            text = HEADER + yaml.safe_dump(content, sort_keys=False, width=120)
        elif name == LEG_FILE:
            text = json.dumps(content, indent=1) + "\n"  # as export_x2_leg_obstacle writes it
        else:
            text = json.dumps(content, indent=2) + "\n"
        (target / name).write_text(text, encoding="utf-8")


def main(argv: list[str] | None = None) -> int:
    argv = sys.argv[1:] if argv is None else argv
    if len(argv) != 2:
        print(__doc__.strip().splitlines()[-1], file=sys.stderr)
        return 2
    source, target = map(Path, argv)
    write(generate(source), target)
    shutil.copymode(source / "robot.yml", target / "robot.yml")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
