    parser.add_argument(
        "--reply-mode",
        type=str,
        choices=["visible", "threaded"],
        default="threaded",
        help="回复模式：threaded=discussion嵌套回复，visible=页面可见评论 (默认: threaded)",
    )
    parser.add_argument(
        "--include-self-comments",
        action="store_true",
        help="在抓取 review 线程时保留当前登录用户自己的评论",
    )
    parser.add_argument(
        "--include-bot-comments",
        action="store_true",
        help="在抓取 review 线程时保留 bot 账号评论",
    )
    parser.add_argument(
        "--resolved",
        type=str,
        default="true",
        help="解决状态：true/false (默认: true)",
    )
    parser.add_argument(
        "--output-dir",
        type=str,
        default="./tmp",
        help="输出目录 (默认: ./tmp)",
    )
    parser.add_argument("--ai-model", type=str, default="ai", help="AI模型名称，用于签名 (默认: ai)")
    parser.add_argument("--dry-run", action="store_true", help="仅显示计划，不执行")

    args = parser.parse_args()

    if args.resume:
        try:
            resume_preview = load_workflow_state(args.resume)
        except Exception as e:
            print(f"\n❌ 无法读取恢复状态: {e}")
            sys.exit(1)
        state_repository = resume_preview["repository"]
        if args.owner is None:
            args.owner = state_repository["owner"]
        if args.repo is None:
            args.repo = state_repository["repo"]
        if args.pr is None:
            args.pr = resume_preview["pr_number"]
        if args.work_dir is None:
            args.work_dir = resume_preview["work_dir"]
    elif args.work_dir is None:
        args.work_dir = "."

    # 警告：如果使用默认的 ai-model，提醒指定真实模型名称
    if args.ai_model == "ai" and not args.resume:
        print("\n⚠️  警告: 未指定 --ai-model 参数，将使用默认值 'ai'")
        print("   建议指定真实模型名称，例如：")
        print("   --ai-model glm-5.2")
        print("   --ai-model gpt-5.6-sol")
        print("   --ai-model claude-fable-5")
        print()

    # 默认行为：如果没有指定任何模式，则使用提取信息模式（AI Agent 友好）
    if not any(
        [
            args.fetch_comments,
            args.apply_fixes,
            args.resume,
            args.reply_comment,
            args.resolve_comment,
            args.resolve_discussion,
        ]
    ):
        args.fetch_comments = True
        print("ℹ️  未指定模式，使用默认的提取信息模式（AI Agent 使用）")

    print("\n" + "=" * 60)
    print("🔧 AtomGit 评审意见处理工具")
    print("=" * 60)

