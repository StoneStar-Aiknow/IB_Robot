# Platform gateway (task 5.1): replaces the retired atomgit_sdk RepairService.
# Every operation routes through the shared CLI boundary, with per-operation
# argv shapes bound to the v0.14.1 capability-matrix evidence:
#   - PR record:      ``pr view <n> -R <slug> --json`` (review_helpers.fetch_pr_record)
#   - comments read:  ``pr comments <n> -R <slug> --json --limit 0`` (0 = all)
#   - current user:   ``user view --json`` (no args = authenticated user)
#   - threaded reply: ``pr reply <n> --discussion <id> --body <text> -R <slug>``
#     (no --body-file/stdin/--json: the body passes verbatim through the
#     boundary's shell=False argument array, and the reply id is left to
#     marker/body-hash reconciliation on resume — design.md D5)
#   - visible reply:  ``pr comment <n> -R <slug> --body-file - [--path --position] --json``
#   - resolve:        ``pr comment resolve|unresolve <n> <discussion-id> -R <slug>``
# The gateway never appends a platform signature: every reply body is signed
# by the caller (``add_ai_signature`` / fix reply formatters), and the SDK's
# trailing "Generated by AtomGit SDK" signature retired with the SDK.
# Write-result policy (tasks 5.1/5.4 gap fix): a reply mutation that was
# attempted but whose acceptance cannot be proven (timeout, nonzero exit)
# raises :class:`UncertainReplyOutcomeError`; auth failures (exit 4) provably
# performed no accepted write and stay retryable. Ownership and resolvability
# are re-proved from the PR-scoped comment list before every write, and
# inline visible replies are validated against the current head diff.
# --------------------------------------------------------------------------- #


def comment_author_login(comment: dict) -> str:
    """Author login of a review comment (``Unknown`` when unreadable; SDK-identical)."""
    author = comment.get("author") or comment.get("user") or {}
    return author.get("username") or author.get("login") or "Unknown"


def comment_anchor_fields(comment: dict) -> dict:
    """Normalized inline-anchor fields of a review comment.

    Shapes are bound to the authenticated v0.14.1 readback evidence
    (``evidence/remote-smoke/25-*``): a real inline ``diff_comment`` carries
    ``diff_position`` as a **dict** (``start_new_line``/``end_new_line``/
    ``position_type``) and — platform limitation — **no file path at all**
    (``diff_file`` is an empty string, there is no ``path``/``new_line``/
    ``old_line`` field). PR-level comments carry ``diff_position=None`` and an
    empty ``diff_file``. Legacy/SDK-era shapes (``position`` as int or dict
    with new_path/new_line) are still accepted; a bare non-dict ``position``
    is kept as anchoring evidence without ever being used as a line number.
    """
    position = comment.get("position")
    position_fields = position if isinstance(position, dict) else {}
    diff_position = comment.get("diff_position")
    diff_position_fields = diff_position if isinstance(diff_position, dict) else {}
    new_line = comment.get("new_line")
    old_line = comment.get("old_line")
    if new_line is None:
        new_line = position_fields.get("new_line")
    if new_line is None and diff_position_fields:
        # Real CLI diff_comment: the anchor is the new-side line range; use
        # the start line (== end line for single-line text positions).
        new_line = diff_position_fields.get("start_new_line")
        if new_line is None:
            new_line = diff_position_fields.get("end_new_line")
    if old_line is None:
        old_line = position_fields.get("old_line")
    return {
        "file_path": (
            comment.get("path")
            or comment.get("diff_file")
            or position_fields.get("new_path")
            or position_fields.get("old_path")
        ),
        "new_line": new_line,
        "old_line": old_line,
        "position": position,
        "diff_position": diff_position,
    }


def comment_is_inline_discussion(comment: dict) -> bool:
    """True when the comment carries diff-anchoring evidence (path/line/position).

    General PR comments carry none of these fields. Per the authenticated
    readback evidence, inline ``diff_comment`` entries anchor exclusively
    through the ``diff_position`` dict (the platform readback exposes no file
    path), so it counts as anchoring evidence here. The AtomGit CLI can only
    resolve inline diff discussions, so this predicate is the resolvability
    gate for ``--resolve-comment``/``--resolve-discussion`` (design.md D4).
    """
    anchor = comment_anchor_fields(comment)
    return bool(
        anchor["file_path"]
        or anchor["new_line"]
        or anchor["old_line"]
        or anchor["position"] is not None
        or anchor["diff_position"] is not None
    )


def coerce_line_number(value) -> int | None:
    """A 1-based line number from an int or digit string; ``None`` otherwise."""
    if isinstance(value, bool):
        return None
    if isinstance(value, int):
        return value
    if isinstance(value, str) and value.strip().isdigit():
        return int(value.strip())
    return None


def is_bot_user(login: str | None) -> bool:
    """Username-rule bot detection (SDK-identical; the read APIs expose no bot flag)."""
    if not login:
        return False
    lowered = login.lower()
    return lowered.endswith("bot") or "[bot]" in lowered or "-bot" in lowered


def should_include_comment(
    comment: dict,
    *,
    current_user: str | None,
    include_self_comments: bool,
    include_bot_comments: bool,
) -> bool:
    login = comment_author_login(comment)
    if not include_self_comments and current_user and login == current_user:
        return False
    return include_bot_comments or not is_bot_user(login)


def serialize_review_comment(base_url: str, comment: dict) -> dict:
    """Thread payload shape consumed by ``unresolved_comments.json`` (SDK-identical).

    ``line`` is derived through :func:`comment_anchor_fields` so real CLI
    ``diff_comment`` entries (anchored via the ``diff_position`` dict) carry
    their new-side line. ``path`` stays empty for them: the authenticated
    readback evidence shows the platform exposes no file path for inline
    comments (``diff_file`` is always an empty string).
    """
    anchor = comment_anchor_fields(comment)
    discussion_anchor = quote(str(comment.get("discussion_id") or comment.get("id")))
    return {
        "id": comment.get("id"),
        "path": anchor["file_path"],
        "position": comment.get("position"),
        "line": anchor["new_line"] or anchor["old_line"],
        "body": comment.get("body"),
        "commit_id": comment.get("commit_id"),
        "discussion_id": comment.get("discussion_id"),
        "user": comment_author_login(comment),
        "comment_type": comment.get("comment_type"),
        "created_at": comment.get("created_at"),
        "updated_at": comment.get("updated_at"),
        "is_outdated": comment.get("is_outdated"),
        "url": f"{base_url}#discussion-{discussion_anchor}",
    }


def build_review_threads(
    base_url: str,
    comments: list[dict],
    *,
    current_user: str | None = None,
    include_self_comments: bool = False,
    include_bot_comments: bool = False,
) -> list[dict]:
    """Group PR comments into discussion threads (retired SDK ``get_review_threads`` port).

    AtomGit/GitCode comment read APIs expose no reliable resolved flag, so
    every fetched discussion is grouped (by ``discussion_id``, falling back
    to the comment id) and self-authored / bot-only threads are filtered out
    by default. A thread survives when at least one of its comments is
    actionable under the filters (SDK-identical semantics).
    """
    grouped: dict[str, list[dict]] = {}
    for comment in comments:
        discussion_id = str(comment.get("discussion_id") or comment.get("id"))
        grouped.setdefault(discussion_id, []).append(comment)

    threads: list[dict] = []
    for thread_comments in grouped.values():
        sorted_comments = sorted(
            thread_comments,
            key=lambda item: (item.get("created_at", ""), item.get("id", 0)),
        )
        actionable = next(
            (
                comment
                for comment in sorted_comments
                if should_include_comment(
                    comment,
                    current_user=current_user,
                    include_self_comments=include_self_comments,
                    include_bot_comments=include_bot_comments,
                )
            ),
            None,
        )
        if actionable is None:
            continue

        latest_comment = sorted_comments[-1]
        thread_payload = serialize_review_comment(base_url, actionable)
        thread_payload.update(
            {
                "thread_size": len(sorted_comments),
                "reply_count": max(0, len(sorted_comments) - 1),
                "participants": sorted(
                    {login for login in (comment_author_login(item) for item in sorted_comments) if login}
                ),
                "latest_comment_id": latest_comment.get("id"),
                "latest_comment_user": comment_author_login(latest_comment),
                "latest_comment_body": latest_comment.get("body"),
                "thread_comments": [
                    {
                        **serialize_review_comment(base_url, item),
                        "is_self": comment_author_login(item) == current_user,
                        "is_bot": is_bot_user(comment_author_login(item)),
                    }
                    for item in sorted_comments
                ],
            }
        )
        threads.append(thread_payload)

    return sorted(threads, key=lambda item: (item.get("created_at", ""), item.get("id", 0)))


class RepairCli:
    """CLI gateway replacing the retired ``atomgit_sdk.services.RepairService``.

    The method surface mirrors the SDK service so the workflow keeps its
    pre-write PR/comment ownership checks and reply/resolve semantics
    (task 5.1): comment and discussion association is always re-proved from
    the PR-scoped comment list before a write, and every write goes through
    the shared boundary exactly once — no retries; attempted-but-unprovable
    writes raise :class:`UncertainReplyOutcomeError` for reconciliation,
    never a blind resend.
    """

    def __init__(self, cli: str, target: atomgit_cli.RepoTarget) -> None:
        self.cli = cli
        self.target = target
        self._current_user_login: str | None = None
        self._current_user_error: str | None = None
        self._current_user_resolved = False

    @property
    def repository(self) -> dict[str, str]:
        return {"owner": self.target.owner, "repo": self.target.repo}

    def get_pr_url(self, pr_number: int) -> str:
        return review_helpers.pr_url(self.target, pr_number)

    def get_pr_record(self, pr_number: int) -> dict:
        """PR metadata via ``pr view --json`` (replaces ``client.get_pull_request``)."""
        return review_helpers.fetch_pr_record(self.cli, self.target, pr_number)

    def get_pr_comments(self, pr_number: int) -> list[dict]:
        """All PR review comments via ``pr comments --json --limit 0`` (0 = all)."""
        return review_helpers.fetch_pr_comments(self.cli, self.target, pr_number)

    def get_current_user_login(self) -> str | None:
        """Authenticated login via ``user view --json``; ``None`` when unreadable.

        A read failure no longer *silently* disables the self filter: the
        failure is recorded (see :meth:`self_filter_status`) so callers must
        surface that the requested filtering could not be applied instead of
        claiming a filtered result.
        """
        if not self._current_user_resolved:
            try:
                result = atomgit_cli.run_json(["user", "view", "--json"], cli=self.cli)
                user = result.require_data()
                if not isinstance(user, dict):
                    raise atomgit_cli.CLIJSONError(
                        f"user view returned {type(user).__name__} instead of a JSON object",
                        argv=result.argv,
                        returncode=result.returncode,
                        stdout=result.stdout,
                        stderr=result.stderr,
                    )
            except atomgit_cli.CLIError as error:
                self._current_user_error = str(error)
                self._current_user_login = None
            else:
                self._current_user_login = user.get("login") or user.get("username") or None
            self._current_user_resolved = True
        return self._current_user_login

    def self_filter_status(self, *, include_self_comments: bool) -> dict:
        """Explicit status of the self-comment filter for a thread fetch.

        Returns ``{"self_filter": "skipped"|"applied"|"unavailable", ...}``;
        ``unavailable`` carries the read failure so the caller can report that
        the requested self filtering was NOT applied (spec: comment discovery
        must not claim a filter it could not perform).
        """
        if include_self_comments:
            return {"self_filter": "skipped", "reason": "include_self_comments requested; no identity read needed"}
        login = self.get_current_user_login()
        if login is not None:
            return {"self_filter": "applied", "current_user": login}
        return {
            "self_filter": "unavailable",
            "reason": self._current_user_error or "authenticated login unreadable via user view",
        }

    def get_review_threads(
        self,
        pr_number: int,
        *,
        include_self_comments: bool = False,
        include_bot_comments: bool = False,
    ) -> list[dict]:
        comments = self.get_pr_comments(pr_number)
        current_user = self.get_current_user_login() if not include_self_comments else None
        return build_review_threads(
            self.get_pr_url(pr_number),
            comments,
            current_user=current_user,
            include_self_comments=include_self_comments,
            include_bot_comments=include_bot_comments,
        )

    def reply_to_comment(
        self,
        pr_number: int,
        comment_id,
        reply_body: str,
        *,
        reply_mode: str = "threaded",
    ) -> dict:
        """Reply to one review comment; comment ownership is re-proved from the PR list."""
        original_comment = self._find_pr_comment(pr_number, comment_id)
        thread_url = self._discussion_thread_url(pr_number, original_comment, comment_id)
        if reply_mode == "visible":
            return self._reply_visible(pr_number, comment_id, original_comment, reply_body, thread_url)
        if reply_mode == "threaded":
            return self._reply_threaded(pr_number, comment_id, original_comment, reply_body, thread_url)
        raise ValueError(f"Unsupported reply mode: {reply_mode}")

    def resolve_comment(self, pr_number: int, comment_id, resolved: bool = True) -> dict:
        """Resolve the discussion containing a comment (comment→discussion via the PR list)."""
        original_comment = self._find_pr_comment(pr_number, comment_id)
        discussion_id = original_comment.get("discussion_id")
        if not discussion_id:
            raise ValueError(f"Comment {comment_id} does not include discussion_id")
        return self.resolve_discussion(pr_number, str(discussion_id), resolved)

    def resolve_discussion(self, pr_number: int, discussion_id: str, resolved: bool = True) -> dict:
        """Resolve/unresolve by discussion id via ``pr comment resolve|unresolve``.

        Ownership and resolvability are re-proved from the PR-scoped, fully
        paginated comment list before the write (design.md D4 gap fix): the
        discussion must belong to this PR (unknown or cross-PR ids never reach
        the platform) and must be an inline diff discussion — a general PR
        comment thread is not resolvable and is refused with an explanation
        instead of marking an unrelated discussion.
        """
        key = str(discussion_id)
        discussion_comments = []
        for comment in self.get_pr_comments(pr_number):
            if not isinstance(comment, dict):
                continue
            comment_pr_number = _comment_pr_number(comment)
            if comment_pr_number is not None and comment_pr_number != pr_number:
                continue
            if str(comment.get("discussion_id") or "") == key:
                discussion_comments.append(comment)
        if not discussion_comments:
            raise ValueError(
                f"discussion {key} was not found in the comment list of PR {pr_number}; "
                "refusing to resolve a discussion id that cannot be proved to belong to this PR"
            )
        if not any(comment_is_inline_discussion(comment) for comment in discussion_comments):
            raise ValueError(
                f"discussion {key} in PR {pr_number} is a general PR comment thread, not an "
                "inline diff discussion; the AtomGit CLI can only resolve inline review discussions"
            )
        action = "resolve" if resolved else "unresolve"
        result = atomgit_cli.run(
            ["pr", "comment", action, str(pr_number), key, "-R", self.target.slug],
            cli=self.cli,
        )
        failure = result.failure()
        if failure is not None:
            raise failure
        return {"discussion_id": key, "resolved": resolved}

    def _find_pr_comment(self, pr_number: int, comment_id) -> dict:
        """Locate one comment inside the PR-scoped list (the CLI has no single-comment read)."""
        key = canonical_comment_id(comment_id)
        for comment in self.get_pr_comments(pr_number):
            if not isinstance(comment, dict) or comment.get("id") is None:
                continue
            try:
                if canonical_comment_id(comment["id"]) != key:
                    continue
            except ValueError:
                continue
            comment_pr_number = _comment_pr_number(comment)
            if comment_pr_number is not None and comment_pr_number != pr_number:
                continue
            return comment
        raise ValueError(f"Comment {comment_id} not found in PR {pr_number}")

    def _discussion_thread_url(self, pr_number: int, comment: dict, comment_id) -> str:
        discussion_id = comment.get("discussion_id") or comment_id
        return f"{self.get_pr_url(pr_number)}#discussion-{quote(str(discussion_id))}"

    def _run_reply_mutation(
        self,
        argv: list[str],
        *,
        stdin_text: str | None = None,
        json_mode: bool = False,
    ) -> atomgit_cli.CLIResult:
        """Run one reply mutation exactly once; unprovable outcomes raise.

        A timeout or a nonzero exit after the mutation argv ran may still have
        been accepted by the platform (task 5.4 fault model), so it surfaces
        as :class:`UncertainReplyOutcomeError` for marker reconciliation.
        Exit 4 (auth) is the exception: no authenticated request was performed
        or the server refused it, which provably accepted nothing and stays
        retryable after ``gitcode auth login``.
        """
        runner = atomgit_cli.run_json if json_mode else atomgit_cli.run
        try:
            result = runner(argv, cli=self.cli, stdin_text=stdin_text)
        except atomgit_cli.CLITimeoutError as error:
            raise UncertainReplyOutcomeError(f"reply outcome is unknown: {error}") from error
        failure = result.failure()
        if failure is not None:
            if isinstance(failure, atomgit_cli.CLIAuthError):
                raise failure
            raise UncertainReplyOutcomeError(f"reply outcome is unknown: {failure}") from failure
        return result

    def _reply_threaded(
        self,
        pr_number: int,
        comment_id,
        original_comment: dict,
        reply_body: str,
        thread_url: str,
    ) -> dict:
        discussion_id = original_comment.get("discussion_id")
        if not discussion_id:
            # The retired SDK fell back to an ``in_reply_to`` POST here; the
            # CLI threaded reply is keyed by discussion id only, so this is an
            # explicit dead end (design.md D4) — the caller is told to use the
            # visible reply mode instead of guessing a thread anchor.
            raise ValueError(
                f"comment {comment_id} carries no discussion_id; the AtomGit CLI threaded "
                "reply (pr reply --discussion) cannot target it — use --reply-mode visible"
            )
        self._run_reply_mutation(
            [
                "pr",
                "reply",
                str(pr_number),
                "--discussion",
                str(discussion_id),
                "--body",
                reply_body,
                "-R",
                self.target.slug,
            ],
        )
        # ``pr reply`` has no ``--json`` (capability matrix A11): no reply id
        # comes back, so the state checkpoint keeps reply_id empty and the
        # marker/body-hash reconciliation assigns it on the next resume (D5).
        payload: dict = {
            "discussion_id": str(discussion_id),
            "thread_url": thread_url,
            "reply_mode": "threaded",
        }
        if original_comment.get("is_outdated"):
            payload["visibility_hint"] = (
                "The target review discussion is outdated; the nested reply may only be visible "
                "after expanding outdated threads in the PR UI."
            )
        return payload

    def _visible_inline_anchor(self, pr_number: int, comment_id, original_comment: dict) -> tuple[str, int] | None:
        """Resolve the inline anchor for a visible reply, or ``None`` for a PR-level original.

        Design.md D4 gap fix. A genuine PR-level original comment (no file/line
        anchoring at all) may be answered with a top-level visible comment. An
        inline original comment must be locatable on the new side of the
        *current* PR head diff — old-side-only, outdated comments without a
        new-side line, files no longer in the diff and lines no longer visible
        are explicit unsupported outcomes with zero platform writes; the reply
        is never silently degraded to a PR-level comment.
        """
        anchor = comment_anchor_fields(original_comment)
        file_path = anchor["file_path"]
        new_line = anchor["new_line"]
        old_line = anchor["old_line"]
        if not (file_path or new_line or old_line or anchor["position"] is not None):
            return None  # a genuine PR-level comment: top-level visible reply is correct
        if not file_path or new_line is None:
            missing = []
            if file_path is None:
                # Authenticated readback evidence: inline diff_comment entries
                # expose no file path (diff_file is always ''), so an inline
                # reply cannot be anchored from the readback alone.
                missing.append("no file path (the AtomGit readback does not expose one for inline comments)")
            if new_line is None:
                missing.append("no new-side line" + (" (old-side only)" if old_line is not None else ""))
            raise ValueError(
                f"comment {comment_id} is an inline review comment whose position cannot be "
                f"located on the new side of the diff ({', '.join(missing)}); a visible inline "
                "reply is unsupported here and is NOT degraded to a PR-level comment "
                "(design.md D4) — post a PR-level reply manually if that is intended"
            )
        line = coerce_line_number(new_line)
        if line is None:
            raise ValueError(
                f"comment {comment_id} carries a non-numeric new_line {new_line!r}; a visible "
                "inline reply is unsupported and is NOT degraded to a PR-level comment (design.md D4)"
            )
        files = review_helpers.fetch_pr_files(self.cli, self.target, pr_number)
        file_entry = next(
            (
                entry
                for entry in files
                if isinstance(entry, dict) and str(entry.get("filename") or "") == str(file_path)
            ),
            None,
        )
        if file_entry is None:
            raise ValueError(
                f"file {file_path} of comment {comment_id} is not part of the current PR head diff; "
                "a visible inline reply is unsupported and is NOT degraded to a PR-level comment "
                "(design.md D4)"
            )
        patch = file_entry.get("patch") or ""
        if isinstance(patch, dict):
            patch = patch.get("diff") or ""
        if line not in review_helpers.diff_new_side_lines(patch):
            raise ValueError(
                f"line {line} of {file_path} is not visible on the new side of the current PR head "
                "diff (the comment may be outdated or the line may have moved); a visible inline "
                "reply is unsupported and is NOT degraded to a PR-level comment (design.md D4)"
            )
        return str(file_path), line

    def _reply_visible(
        self,
        pr_number: int,
        comment_id,
        original_comment: dict,
        reply_body: str,
        thread_url: str,
    ) -> dict:
        visible_body = f"Reply to review comment #{comment_id}\nOriginal thread: {thread_url}\n\n{reply_body}"
        anchor = self._visible_inline_anchor(pr_number, comment_id, original_comment)
        if anchor is None:
            argv = [
                "pr",
                "comment",
                str(pr_number),
                "-R",
                self.target.slug,
                "--body-file",
                "-",
                "--json",
            ]
            visibility_hint = (
                "Posted as a visible PR comment because the original comment is a PR-level "
                "comment and nested discussion replies are not reliably shown in AtomGit UI."
            )
        else:
            file_path, line_number = anchor
            # ``pr comment --position`` is the NEW-side line number (pr-comment
            # help evidence), re-proved against the current head diff above.
            argv = [
                "pr",
                "comment",
                str(pr_number),
                "-R",
                self.target.slug,
                "--body-file",
                "-",
                "--path",
                file_path,
                "--position",
                str(line_number),
                "--json",
            ]
            visibility_hint = (
                "Posted as a visible inline comment because nested discussion replies "
                "are not reliably shown in AtomGit UI."
            )
        result = self._run_reply_mutation(argv, stdin_text=visible_body, json_mode=True)
        data = result.data if isinstance(result.data, dict) else {}
        return {**data, "thread_url": thread_url, "reply_mode": "visible", "visibility_hint": visibility_hint}


def load_pr_git_context(work_dir: str, api: RepairCli, pr_number: int) -> PRGitContext:
    """Load and validate immutable base/head/source data before any local write."""
    pr = api.get_pr_record(pr_number)
    if not isinstance(pr, dict):
        raise RuntimeError("PR metadata response is not an object")
    base = pr.get("base")
    head = pr.get("head")
    if not isinstance(base, dict) or not isinstance(head, dict):
        raise RuntimeError("PR metadata is missing base/head objects")

    base_sha = base.get("sha")
    head_sha = head.get("sha")
    head_branch = head.get("ref")
    head_repo = head.get("repo")
    for name, value in (("base.sha", base_sha), ("head.sha", head_sha)):
        if not isinstance(value, str) or re.fullmatch(r"[0-9a-fA-F]{40,64}", value) is None:
            raise RuntimeError(f"PR metadata is missing a full commit OID in {name}")
    if not isinstance(head_branch, str) or not head_branch:
        raise RuntimeError("PR metadata is missing head.ref")
    if not isinstance(head_repo, dict):
        raise RuntimeError("PR metadata is missing head.repo")

    base_sha = base_sha.lower()
    head_sha = head_sha.lower()
    if _resolve_commit(work_dir, base_sha, "PR base SHA") != base_sha:
        raise RuntimeError(f"local object for PR base SHA does not resolve exactly to {base_sha}")
    if _resolve_commit(work_dir, head_sha, "PR head SHA") != head_sha:
        raise RuntimeError(f"local object for PR head SHA does not resolve exactly to {head_sha}")
    local_head = _resolve_commit(work_dir, "HEAD", "local HEAD")
    if local_head != head_sha:
        raise RuntimeError(
            f"local HEAD {local_head[:12]} does not match PR head {head_sha[:12]}; "
            "check out and update the PR source branch before applying fixes"
        )

    _require_ancestor(
        work_dir,
        base_sha,
        local_head,
        (
            f"PR metadata base {base_sha[:12]} is not an ancestor of local HEAD {local_head[:12]}; "
            "refusing to rebase onto a sibling or advanced target history"
        ),
    )
    ensure_no_merge_commits(work_dir, base_sha, local_head)

    branch_check = subprocess.run(
        ["git", "check-ref-format", "--branch", head_branch],
        cwd=work_dir,
        capture_output=True,
        text=True,
    )
    if branch_check.returncode != 0:
        raise RuntimeError(f"PR head.ref is not a valid branch name: {head_branch}")

    source_push_url = _find_source_push_url(work_dir, head_repo)
    return PRGitContext(
        base_sha=base_sha,
        head_sha=head_sha,
        head_branch=head_branch,
        source_push_url=source_push_url,
        source_ref=f"refs/heads/{head_branch}",
    )


def verify_fixup_target(work_dir: str, fixup_target: str, base_sha: str) -> str:
    """验证目标 commit 位于不可变的 PR base SHA 与 HEAD 之间。

    autosquash 只会重放 base SHA..HEAD 内的 commit; 目标在范围外 (如 base 本身、
    另一条分支上的 commit) 时, fixup! commit 会被原样重放为普通 commit, 污染
    PR 历史，因此必须在任何文件写入前拒绝。
    """
    target_sha = _resolve_commit(work_dir, fixup_target, "fixup target")
    _require_ancestor(
        work_dir,
        base_sha,
        "HEAD",
        f"PR base SHA {base_sha[:12]} is not an ancestor of HEAD; refusing to rewrite history",
    )

    rng = subprocess.run(
        ["git", "rev-list", f"{base_sha}..HEAD"],
        cwd=work_dir,
        capture_output=True,
        text=True,
    )
    if rng.returncode != 0:
        raise RuntimeError(f"failed to list {base_sha}..HEAD: {rng.stderr.strip()}")
    if target_sha not in rng.stdout.split():
        raise RuntimeError(
            f"fixup target {fixup_target} ({target_sha[:12]}) is not within "
            f"{base_sha}..HEAD, so autosquash cannot fold it back and it would "
            f"be replayed as a normal fixup! commit. Pick a target from: "
            f"git log --oneline {base_sha}..HEAD"
        )
    return target_sha


def build_fix_plan(
    fixes: list[dict],
    work_dir: str,
    base_sha: str | None,
    default_fixup_target: str | None,
) -> list[PlannedFix]:
    plans = []
    for fix in fixes:
        fix_type = fix.get("type", "code_fix")
        rel_path = fix.get("file_path") if fix_type in CODE_FIX_TYPES else None
        abs_path = None
        if fix_type in CODE_FIX_TYPES:
            abs_path = resolve_repo_path(work_dir, rel_path)
            rel_path = Path(abs_path).relative_to(Path(work_dir).resolve()).as_posix()
        target_sha = None
        if fix_type in CODE_FIX_TYPES:
            if base_sha is None:
                raise RuntimeError("code fixes require validated PR base metadata")
            target_sha = verify_fixup_target(
                work_dir,
                requested_fixup_target(fix, default_fixup_target),
                base_sha,
            )
        plans.append(
            PlannedFix(
                payload=fix,
                fix_type=fix_type,
                rel_path=rel_path,
                abs_path=abs_path,
                target_sha=target_sha,
            )
        )

    plans_by_path: dict[str, list[PlannedFix]] = {}
    for plan in plans:
        if plan.rel_path is not None:
            plans_by_path.setdefault(plan.rel_path, []).append(plan)

    ambiguous = sorted(
        path
        for path, path_plans in plans_by_path.items()
        if len({plan.target_sha for plan in path_plans if plan.target_sha is not None}) > 1
    )
    if ambiguous:
        raise ValueError(
            "one file cannot be staged into multiple fixup targets in a single non-interactive batch: "
            f"{', '.join(ambiguous)}; split these fixes into separate confirmed runs"
        )

    merged_plans = []
    emitted_paths = set()
    for plan in plans:
        if plan.rel_path is None:
            merged_plans.append(plan)
            continue
        if plan.rel_path in emitted_paths:
            continue
        emitted_paths.add(plan.rel_path)
        same_path = plans_by_path[plan.rel_path]
        if len(same_path) == 1:
            merged_plans.append(plan)
            continue
        if any(item.fix_type != "delete_lines" for item in same_path):
            raise ValueError(
                "multiple fixes for one file are unsafe unless every fix is delete_lines against the same snapshot: "
                f"{plan.rel_path}; combine them into one confirmed patch"
            )

        merged_payload = dict(plan.payload)
        merged_payload["delete_lines"] = sorted(
            {line for item in same_path for line in item.payload["delete_lines"]},
            reverse=True,
        )
        merged_plans.append(
            PlannedFix(
                payload=merged_payload,
                fix_type="delete_lines",
                rel_path=plan.rel_path,
                abs_path=plan.abs_path,
                target_sha=plan.target_sha,
                reply_payloads=tuple(item.payload for item in same_path),
            )
        )
    return merged_plans


class FixTransaction:
    """Own file snapshots, temporary fixup commits, and this run's rebase state."""

    def __init__(
        self,
        work_dir: str,
        base_sha: str,
        plans: list[PlannedFix],
        expected_head: str | None = None,
    ):
        self.work_dir = work_dir
        self.base_sha = base_sha
        self.plans = plans
        self.expected_head = expected_head
        self.paths = sorted({plan.rel_path for plan in plans if plan.rel_path is not None})
        self.snapshot: dict[str, FileSnapshot] = {}
        self.original_head = ""
        self.rebase_started = False

    def __enter__(self):
        ensure_no_rebase_in_progress(self.work_dir)
        ensure_clean_index(self.work_dir)
        ensure_clean_worktree(self.work_dir)
        self.original_head = _resolve_commit(self.work_dir, "HEAD", "local HEAD")
        if self.expected_head is not None and self.original_head != self.expected_head:
            raise RuntimeError(
                f"local HEAD changed during preflight: expected {self.expected_head[:12]}, "
                f"got {self.original_head[:12]}"
            )
        ensure_no_merge_commits(self.work_dir, self.base_sha, self.original_head)
        for plan in self.plans:
            if plan.abs_path is not None:
                snapshot_file(self.snapshot, plan.abs_path)
        return self

    def commit_group(self, target_sha: str, group: list[PlannedFix]) -> None:
        paths = sorted({plan.rel_path for plan in group if plan.rel_path is not None})
        if not paths:
            raise ValueError(f"fixup group {target_sha[:12]} has no files to stage")
        add = subprocess.run(
            ["git", "add", "--", *paths],
            cwd=self.work_dir,
            env=literal_pathspec_env(),
            capture_output=True,
            text=True,
        )
        if add.returncode != 0:
            raise RuntimeError(f"Git add failed for fixup target {target_sha[:12]}: {add.stderr.strip()}")

        diff = subprocess.run(
            ["git", "diff", "--cached", "--quiet", "--", *paths],
            cwd=self.work_dir,
            env=literal_pathspec_env(),
            capture_output=True,
            text=True,
        )
        if diff.returncode == 0:
            raise RuntimeError(
                f"fixes for target {target_sha[:12]} produced no staged diff; refusing to create a false fixup"
            )
        if diff.returncode != 1:
            raise RuntimeError(f"failed to inspect staged fixes for {target_sha[:12]}: {diff.stderr.strip()}")

        commit = subprocess.run(
            ["git", "commit", f"--fixup={target_sha}"],
            cwd=self.work_dir,
            capture_output=True,
            text=True,
        )
        if commit.returncode != 0:
            raise RuntimeError(f"Git commit --fixup failed for {target_sha[:12]}: {commit.stderr.strip()}")
        print(f"  ✓ 已创建 fixup commit -> {target_sha[:12]} ({len(paths)} files)")

    def autosquash(self) -> None:
        ensure_no_merge_commits(self.work_dir, self.base_sha, "HEAD")
        env = os.environ.copy()
        env["GIT_SEQUENCE_EDITOR"] = "true"
        self.rebase_started = True
        result = subprocess.run(
            ["git", "rebase", "-i", "--autosquash", self.base_sha],
            cwd=self.work_dir,
            env=env,
            capture_output=True,
            text=True,
        )
        if result.returncode != 0:
            raise RuntimeError(f"autosquash failed: {result.stderr.strip()}")
        self.rebase_started = False

        leftover = subprocess.run(
            ["git", "log", "--format=%s", f"{self.base_sha}..HEAD"],
            cwd=self.work_dir,
            capture_output=True,
            text=True,
        )
        if leftover.returncode != 0:
            raise RuntimeError(f"failed to verify autosquash result: {leftover.stderr.strip()}")
        residual = [subject for subject in leftover.stdout.splitlines() if subject.startswith("fixup!")]
        if residual:
            raise RuntimeError(
                f"autosquash completed but {len(residual)} fixup commit(s) remain: {'; '.join(residual[:3])}"
            )

    def __exit__(self, exc_type, exc, _traceback):
        if exc_type is None:
            return False

        cleanup_errors = []
        history_normalized = False
        try:
            rebase_active = False
            if self.rebase_started:
                try:
                    rebase_active = rebase_in_progress(self.work_dir)
                except BaseException as cleanup_error:
                    cleanup_errors.append(f"failed to inspect rebase state: {cleanup_error}")

            if rebase_active and not cleanup_errors:
                try:
                    abort = subprocess.run(
                        ["git", "rebase", "--abort"],
                        cwd=self.work_dir,
                        capture_output=True,
                        text=True,
                    )
                    if abort.returncode != 0:
                        cleanup_errors.append(f"git rebase --abort failed: {abort.stderr.strip()}")
                except BaseException as cleanup_error:
                    cleanup_errors.append(f"git rebase --abort raised: {cleanup_error}")

            if not cleanup_errors:
                try:
                    reset = subprocess.run(
                        ["git", "reset", "--soft", self.original_head],
                        cwd=self.work_dir,
                        capture_output=True,
                        text=True,
                    )
                    if reset.returncode != 0:
                        cleanup_errors.append(
                            f"git reset --soft {self.original_head[:12]} failed: {reset.stderr.strip()}"
                        )
                except BaseException as cleanup_error:
                    cleanup_errors.append(f"git reset --soft raised: {cleanup_error}")

            if not cleanup_errors:
                try:
                    unstage = subprocess.run(
                        ["git", "restore", "--staged", "--", *self.paths],
                        cwd=self.work_dir,
                        env=literal_pathspec_env(),
                        capture_output=True,
                        text=True,
                    )
                    if unstage.returncode != 0:
                        cleanup_errors.append(f"failed to unstage transaction paths: {unstage.stderr.strip()}")
                    else:
                        history_normalized = True
                except BaseException as cleanup_error:
                    cleanup_errors.append(f"unstaging transaction paths raised: {cleanup_error}")
        finally:
            if history_normalized:
                try:
                    restore_snapshot(self.snapshot)
                except BaseException as restore_error:
                    cleanup_errors.append(f"failed to restore file snapshots: {restore_error}")

        if cleanup_errors:
            raise RepoStateNotNormalizedError(
                f"{exc}\nTransaction cleanup was incomplete: {'; '.join(cleanup_errors)}. "
                "Do not re-run blindly; inspect git status and git log first."
            ) from exc
        return False


def push_command(context: PRGitContext) -> list[str]:
    return [
        "git",
        "push",
        f"--force-with-lease={context.source_ref}:{context.head_sha}",
        context.source_push_url,
        f"HEAD:{context.source_ref}",
    ]


def push_and_verify(work_dir: str, context: PRGitContext) -> str:
    """Push to the PR source ref with an OID-bound lease and verify the remote ref."""
    new_head = _resolve_commit(work_dir, "HEAD", "rewritten HEAD")
    result = subprocess.run(
        push_command(context),
        cwd=work_dir,
        capture_output=True,
        text=True,
    )
    if result.returncode != 0:
        raise RuntimeError(f"push failed; explicit lease preserved the remote branch: {result.stderr.strip()}")

    remote = subprocess.run(
        ["git", "ls-remote", "--exit-code", "--refs", context.source_push_url, context.source_ref],
        cwd=work_dir,
        capture_output=True,
        text=True,
    )
    if remote.returncode != 0:
        raise RuntimeError(
            "push returned success but the PR source ref could not be verified; no review replies were sent: "
            f"{remote.stderr.strip()}"
        )
    remote_oids = {line.split()[0].lower() for line in remote.stdout.splitlines() if line.split()}
    if remote_oids != {new_head}:
        raise RuntimeError(
            f"PR source ref verification mismatch: expected {new_head}, got {', '.join(sorted(remote_oids)) or 'none'}"
        )
    return new_head


def read_remote_ref(work_dir: str, push_url: str, source_ref: str) -> str | None:
    remote = subprocess.run(
        ["git", "ls-remote", "--exit-code", "--refs", push_url, source_ref],
        cwd=work_dir,
        capture_output=True,
        text=True,
    )
    if remote.returncode == 2:
        return None
    if remote.returncode != 0:
        raise RuntimeError(f"failed to read remote ref {source_ref} from exact push URL: {remote.stderr.strip()}")
    remote_oids = {line.split()[0].lower() for line in remote.stdout.splitlines() if line.split()}
    if len(remote_oids) != 1:
        raise RuntimeError(f"remote ref {source_ref} returned {len(remote_oids)} OIDs; refusing ambiguous resume state")
    return remote_oids.pop()


def resume_push(state_path: str, state: dict) -> None:
    git_state = state.get("git")
    if git_state is None:
        return
    work_dir = state["work_dir"]
    old_head = git_state["old_head"]
    new_head = git_state["new_head"]
    if new_head is None:
        raise RuntimeError("resume state does not contain rewritten git.new_head")

    git_state["push_status"] = "pending"
    state["status"] = STATUS_PENDING_PUSH
    state["last_error"] = None
    write_workflow_state(state_path, state)

    local_head = _resolve_commit(work_dir, "HEAD", "local HEAD")
    if local_head not in {old_head, new_head}:
        raise RuntimeError(
            f"local HEAD {local_head[:12]} is neither recorded old_head {old_head[:12]} nor new_head {new_head[:12]}"
        )
    if _resolve_commit(work_dir, new_head, "rewritten HEAD") != new_head:
        raise RuntimeError(f"rewritten commit object {new_head} is not available locally")

    remote_head = read_remote_ref(work_dir, git_state["push_url"], git_state["source_ref"])
    if remote_head == new_head:
        git_state["push_status"] = "verified"
        state["status"] = STATUS_PENDING_REPLIES
        state["last_error"] = None
        write_workflow_state(state_path, state)
        return
    if remote_head != old_head:
        raise RuntimeError(
            "remote source ref is neither the recorded old_head nor new_head; refusing to overwrite concurrent work: "
            f"{remote_head or 'missing'}"
        )

    command = [
        "git",
        "push",
        f"--force-with-lease={git_state['source_ref']}:{old_head}",
        git_state["push_url"],
        f"{new_head}:{git_state['source_ref']}",
    ]
    result = subprocess.run(command, cwd=work_dir, capture_output=True, text=True)
    if result.returncode != 0:
        raise RuntimeError(f"resume push failed; explicit lease preserved the remote branch: {result.stderr.strip()}")
    verified_head = read_remote_ref(work_dir, git_state["push_url"], git_state["source_ref"])
    if verified_head != new_head:
        raise RuntimeError(f"resume push verification mismatch: expected {new_head}, got {verified_head or 'missing'}")
    git_state["push_status"] = "verified"
    state["status"] = STATUS_PENDING_REPLIES
    state["last_error"] = None
    write_workflow_state(state_path, state)


def format_fix_payload_reply(fix: dict, ai_model: str) -> str:
    fix_type = fix.get("type", "code_fix")
    if fix_type == "code_fix":
        return format_fix_reply(fix, ai_model)
    if fix_type == "delete_lines":
        return format_delete_lines_reply(fix, ai_model)
    if fix_type == "revert_file":
        return format_revert_reply(fix, ai_model)
    return format_logic_reply(fix, ai_model)


def planned_reply_payloads(plan: PlannedFix) -> tuple[dict, ...]:
    return plan.reply_payloads or (plan.payload,)


def apply_planned_fix(plan: PlannedFix, work_dir: str, base_sha: str) -> None:
    if plan.abs_path is None:
        raise RuntimeError(f"{plan.fix_type} has no resolved file path")
    if plan.fix_type == "code_fix":
        apply_code_fix(plan.abs_path, plan.payload["original_code"], plan.payload["fixed_code"])
    elif plan.fix_type == "delete_lines":
        delete_specific_lines(plan.abs_path, plan.payload["delete_lines"])
    elif plan.fix_type == "revert_file":
        revert_file(plan.abs_path, work_dir, base_sha)
    else:
        raise RuntimeError(f"cannot apply non-code fix type: {plan.fix_type}")


def canonical_comment_id(comment_id: object) -> str:
    if isinstance(comment_id, bool) or not isinstance(comment_id, int | str):
        raise ValueError(f"comment_id must be an integer or non-empty string, got {comment_id!r}")
    value = str(comment_id).strip()
    if not value:
        raise ValueError("comment_id must not be empty")
    return value


def list_pr_comments(api: RepairCli, pr_number: int) -> list[dict]:
    """PR-scoped, fully paginated comment list via ``pr comments --json --limit 0``."""
    comments = api.get_pr_comments(pr_number)
    if not isinstance(comments, list):
        raise RuntimeError("PR comments response is not a list")
    return comments


def _comment_pr_number(comment: dict) -> int | None:
    for key in ("pull_request_number", "pr_number", "number"):
        value = comment.get(key)
        if isinstance(value, int) and not isinstance(value, bool):
            return value
        if isinstance(value, str) and value.isdigit():
            return int(value)
    pull_request = comment.get("pull_request")
    if isinstance(pull_request, dict):
        value = pull_request.get("number") or pull_request.get("id")
        if isinstance(value, int) and not isinstance(value, bool):
            return value
        if isinstance(value, str) and value.isdigit():
            return int(value)
    return None


def validate_pr_comment_ids(api: RepairCli, pr_number: int, comment_ids: list[object]) -> dict[str, dict]:
    """Validate comment IDs against the PR-scoped, fully paginated CLI result."""
    comments = list_pr_comments(api, pr_number)

    metadata: dict[str, dict] = {}
    for comment in comments:
        if not isinstance(comment, dict) or comment.get("id") is None:
            continue
        try:
            key = canonical_comment_id(comment["id"])
        except ValueError:
            continue
        comment_pr_number = _comment_pr_number(comment)
        if comment_pr_number is not None and comment_pr_number != pr_number:
            continue
        metadata[key] = {
            "comment_id": comment["id"],
            "discussion_id": comment.get("discussion_id"),
            "comment_type": comment.get("comment_type"),
            "path": comment.get("path") or comment.get("diff_file"),
            "is_outdated": comment.get("is_outdated"),
        }

    requested = [canonical_comment_id(comment_id) for comment_id in comment_ids]
    missing = sorted({comment_id for comment_id in requested if comment_id not in metadata})
    if missing:
        raise ValueError(f"comment_id values do not belong to target PR #{pr_number}: {', '.join(missing)}")
    return {comment_id: metadata[comment_id] for comment_id in requested}


def build_reply_specs(
    plans: list[PlannedFix],
    ai_model: str,
    comment_metadata: dict[str, dict],
) -> list[dict]:
    specs = []
    for plan in plans:
        for payload in planned_reply_payloads(plan):
            metadata = comment_metadata[canonical_comment_id(payload["comment_id"])]
            specs.append(
                {
                    **metadata,
                    "body": format_fix_payload_reply(payload, ai_model),
                }
            )
    return specs


def _timestamp() -> str:
    return datetime.now().isoformat()


def _reply_counts(state: dict) -> dict[str, int]:
    replies = state.get("replies", [])
    return {
        "total": len(replies),
        "pending": sum(entry.get("status") == "pending" for entry in replies),
        "sent": sum(entry.get("status") == "sent" for entry in replies),
        "uncertain": sum(
            entry.get("status") == "pending" and bool(entry.get("uncertain_outcome")) for entry in replies
        ),
    }


def write_workflow_state(state_path: str | Path, state: dict) -> None:
    """Atomically checkpoint a machine-readable workflow ledger."""
    path = Path(state_path).resolve()
    path.parent.mkdir(parents=True, exist_ok=True)
    state["updated_at"] = _timestamp()
    state["reply_counts"] = _reply_counts(state)

    fd, temporary_path = tempfile.mkstemp(prefix=f".{path.name}.", suffix=".tmp", dir=path.parent)
    try:
        with os.fdopen(fd, "w", encoding="utf-8") as state_file:
            json.dump(state, state_file, indent=2, ensure_ascii=False, sort_keys=True)
            state_file.write("\n")
            state_file.flush()
            os.fsync(state_file.fileno())
        os.replace(temporary_path, path)
    except BaseException:
        with suppress(FileNotFoundError):
            os.remove(temporary_path)
        raise


def _state_repository(api: RepairCli) -> dict[str, str]:
    repository = api.repository
    if not repository.get("owner") or not repository.get("repo"):
        raise RuntimeError("CLI target is missing repository owner/repo")
    return repository


def create_workflow_state(
    args,
    api: RepairCli,
    reply_specs: list[dict],
    context: PRGitContext | None,
) -> tuple[str, dict]:
    transaction_id = uuid.uuid4().hex
    created_at = _timestamp()
    replies = []
    for index, spec in enumerate(reply_specs, 1):
        unsigned_body = spec["body"]
        content_hash = hashlib.sha256(unsigned_body.encode("utf-8")).hexdigest()
        marker = f"<!-- {REPLY_MARKER_PREFIX}:{transaction_id}:{index}:{content_hash} -->"
        body = f"{unsigned_body}\n\n{marker}"
        replies.append(
            {
                "comment_id": spec["comment_id"],
                "discussion_id": spec.get("discussion_id"),
                "comment_type": spec.get("comment_type"),
                "path": spec.get("path"),
                "is_outdated": spec.get("is_outdated"),
                "body": body,
                "body_sha256": hashlib.sha256(body.encode("utf-8")).hexdigest(),
                "marker": marker,
                "status": "pending",
                "attempts": 0,
                # An attempt whose acceptance could not be proven; such entries
                # are only ever cleared by marker/body-hash reconciliation and
                # are never auto-resent on a marker-less comment list (D5).
                "uncertain_outcome": False,
                "reply_id": None,
                "last_error": None,
            }
        )

    output_dir = Path(getattr(args, "output_dir", "./tmp")).resolve()
    repository = _state_repository(api)
    repo_slug = repository["repo"].lower().replace("-", "_")
    state_path = output_dir / f"{repo_slug}_pr_{args.pr}_review_resolution_{transaction_id}.json"
    git_state = None
    status = STATUS_PENDING_REPLIES
    if context is not None:
        status = "applying"
        git_state = {
            "base_sha": context.base_sha,
            "old_head": context.head_sha,
            "new_head": None,
            "push_url": context.source_push_url,
            "source_ref": context.source_ref,
            "head_branch": context.head_branch,
            "push_status": "pending",
        }
    state = {
        "schema_version": STATE_SCHEMA_VERSION,
        # Provenance marker (schema v2): the state's producing gateway. Legacy
        # SDK-era v1 states carry no provenance and their reply/identity
        # semantics were never proven equivalent on the real platform, so they
        # are refused without side effects (design.md D5; SKILL.md schema 政策).
        "state_provenance": {"producer": STATE_PRODUCER},
        "transaction_id": transaction_id,
        "status": status,
        "created_at": created_at,
        "updated_at": created_at,
        "state_file": str(state_path),
        "repository": repository,
        "pr_number": args.pr,
        "work_dir": str(Path(args.work_dir).resolve()),
        "reply_mode": args.reply_mode,
        "git": git_state,
        "replies": replies,
        "last_error": None,
    }
    write_workflow_state(state_path, state)
    return str(state_path), state


def load_workflow_state(state_path: str | Path) -> dict:
    path = Path(state_path).resolve()
    with open(path, encoding="utf-8") as state_file:
        state = json.load(state_file)
    if not isinstance(state, dict):
        raise ValueError("resume state must be a JSON object")
    if state.get("schema_version") != STATE_SCHEMA_VERSION:
        raise ValueError(
            f"unsupported resume state schema_version: {state.get('schema_version')!r} "
            f"(supported: {STATE_SCHEMA_VERSION} with the '{STATE_PRODUCER}' provenance marker). "
            "Legacy SDK-era v1 states are rejected: CLI identity/marker/transaction equivalence "
            "has not been verified against the real platform, so resume is refused without side "
            "effects — keep the state file and reconcile the PR page manually"
        )
    provenance = state.get("state_provenance")
    if not isinstance(provenance, dict) or provenance.get("producer") != STATE_PRODUCER:
        raise ValueError(
            f"resume state is missing the '{STATE_PRODUCER}' provenance marker: {provenance!r}; "
            "refusing to resume a state whose producing gateway cannot be verified"
        )
    if not isinstance(state.get("transaction_id"), str) or not state["transaction_id"]:
        raise ValueError("resume state is missing transaction_id")
    if not isinstance(state.get("pr_number"), int):
        raise ValueError("resume state is missing integer pr_number")
    if state.get("reply_mode") not in {"threaded", "visible"}:
        raise ValueError("resume state has invalid reply_mode")
    repository = state.get("repository")
    if not isinstance(repository, dict) or not all(
        isinstance(repository.get(key), str) and repository[key] for key in ("owner", "repo")
    ):
        raise ValueError("resume state is missing repository owner/repo")
    if not isinstance(state.get("work_dir"), str) or not state["work_dir"]:
        raise ValueError("resume state is missing work_dir")
    if state.get("status") not in {
        "applying",
        STATUS_PENDING_PUSH,
        STATUS_PENDING_REPLIES,
        STATUS_SUCCESS,
        STATUS_FAILED,
    }:
        raise ValueError(f"resume state has invalid status: {state.get('status')!r}")

    replies = state.get("replies")
    if not isinstance(replies, list):
        raise ValueError("resume state replies must be a list")
    for index, entry in enumerate(replies, 1):
        if not isinstance(entry, dict):
            raise ValueError(f"resume reply #{index} is not an object")
        canonical_comment_id(entry.get("comment_id"))
        body = entry.get("body")
        marker = entry.get("marker")
        if not isinstance(body, str) or not isinstance(marker, str) or marker not in body:
            raise ValueError(f"resume reply #{index} has invalid body/marker")
        body_hash = hashlib.sha256(body.encode("utf-8")).hexdigest()
        if entry.get("body_sha256") != body_hash:
            raise ValueError(f"resume reply #{index} body hash mismatch")
        if entry.get("status") not in {"pending", "sent"}:
            raise ValueError(f"resume reply #{index} has invalid status")
        if "uncertain_outcome" in entry and not isinstance(entry["uncertain_outcome"], bool):
            raise ValueError(f"resume reply #{index} has a non-boolean uncertain_outcome")
        if entry.get("status") == "sent" and entry.get("uncertain_outcome"):
            raise ValueError(f"resume reply #{index} is sent but still flagged uncertain")

    git_state = state.get("git")
    if git_state is not None:
        if not isinstance(git_state, dict):
            raise ValueError("resume state git field must be an object or null")
        for field in ("base_sha", "old_head"):
            value = git_state.get(field)
            if not isinstance(value, str) or re.fullmatch(r"[0-9a-f]{40,64}", value) is None:
                raise ValueError(f"resume state git.{field} is not a full lowercase OID")
        new_head = git_state.get("new_head")
        if new_head is not None and (
            not isinstance(new_head, str) or re.fullmatch(r"[0-9a-f]{40,64}", new_head) is None
        ):
            raise ValueError("resume state git.new_head is not a full lowercase OID or null")
        if not isinstance(git_state.get("push_url"), str) or not git_state["push_url"]:
            raise ValueError("resume state is missing exact git.push_url")
        if _normalize_git_repo_url(git_state["push_url"]) is None:
            raise ValueError("resume state git.push_url is not a supported Git URL")
        source_ref = git_state.get("source_ref")
        if not isinstance(source_ref, str) or not source_ref.startswith("refs/heads/"):
            raise ValueError("resume state has invalid git.source_ref")
        if git_state.get("push_status") not in {"pending", "verified"}:
            raise ValueError("resume state has invalid git.push_status")
        if state["status"] in {STATUS_PENDING_PUSH, STATUS_PENDING_REPLIES, STATUS_SUCCESS} and new_head is None:
            raise ValueError(f"resume state status {state['status']} requires git.new_head")
        if state["status"] in {STATUS_PENDING_REPLIES, STATUS_SUCCESS} and git_state["push_status"] != "verified":
            raise ValueError(f"resume state status {state['status']} requires a verified push")
    elif state["status"] == STATUS_PENDING_PUSH:
        raise ValueError("resume state pending_push requires git metadata")
    if state["status"] == STATUS_SUCCESS and any(entry["status"] != "sent" for entry in replies):
        raise ValueError("resume state success requires every reply to be sent")
    state["state_file"] = str(path)
    return state


def _remote_reply_for_entry(entry: dict, comments: list[dict]) -> dict | None:
    for comment in comments:
        if not isinstance(comment, dict):
            continue
        body = comment.get("body")
        if not isinstance(body, str):
            continue
        if entry["marker"] in body or hashlib.sha256(body.encode("utf-8")).hexdigest() == entry["body_sha256"]:
            return comment
    return None


def reconcile_state_replies(api: RepairCli, state_path: str, state: dict) -> None:
    pending = [entry for entry in state["replies"] if entry["status"] == "pending"]
    if not pending:
        return
    comments = list_pr_comments(api, state["pr_number"])
    changed = False
    for entry in pending:
        remote_reply = _remote_reply_for_entry(entry, comments)
        if remote_reply is None:
            continue
        entry["status"] = "sent"
        entry["reply_id"] = remote_reply.get("id")
        entry["last_error"] = None
        # Marker/body-hash proof of acceptance supersedes any uncertain flag.
        entry["uncertain_outcome"] = False
        changed = True
    if changed:
        write_workflow_state(state_path, state)


def _report_uncertain_replies(state: dict) -> None:
    unknown = [entry for entry in state["replies"] if entry["status"] == "pending" and entry.get("uncertain_outcome")]
    if not unknown:
        return
    print(f"\n❓ {len(unknown)} 条回复结果未知（已尝试发送但无法确认平台是否接受，已阻止自动重发）:")
    for entry in unknown:
        print(f"   - 评论 #{entry['comment_id']}: 请在 PR 页面人工核对该评论线程。")
        print("     仅当人工确认未发布后，才可将状态文件中该项 uncertain_outcome 改为 false 再恢复；")
        print("     一次列表读取看不到 marker 不构成重发依据（marker 可能被剥离/分页缺失/延迟可见）。")


def send_state_replies(api: RepairCli, state_path: str, state: dict) -> bool:
    try:
        reconcile_state_replies(api, state_path, state)
    except Exception as error:
        state["last_error"] = f"reply reconciliation failed before send: {error}"
        write_workflow_state(state_path, state)
        raise
    pending_count = sum(
        entry["status"] == "pending" and not entry.get("uncertain_outcome") for entry in state["replies"]
    )
    if pending_count:
        print(f"\n💬 发送 {pending_count} 条待处理回复...")

    for entry in state["replies"]:
        if entry["status"] != "pending":
            continue
        if entry.get("uncertain_outcome"):
            # Attempted before, acceptance unproven: only reconciliation (a
            # marker/body-hash match above) may clear this entry. A single
            # marker-less comment list is NOT resend evidence — the reply may
            # be accepted with the marker stripped, paginated away or not yet
            # visible (design.md D5; spec "Marker disappears in readback").
            continue
        entry["attempts"] += 1
        entry["last_error"] = None
        # Pre-send checkpoint marks the outcome unknown BEFORE the mutation:
        # a crash mid-write leaves uncertain_outcome=True on disk, so the
        # resume path can never blindly resend across that window.
        entry["uncertain_outcome"] = True
        write_workflow_state(state_path, state)
        try:
            result = api.reply_to_comment(
                state["pr_number"],
                entry["comment_id"],
                entry["body"],
                reply_mode=state["reply_mode"],
            )
        except KeyboardInterrupt as error:
            # The interrupt may have landed after the platform accepted the
            # write; keep the uncertain flag so resume reconciles first.
            entry["last_error"] = str(error)
            state["status"] = STATUS_PENDING_REPLIES
            state["last_error"] = f"reply to comment {entry['comment_id']} interrupted: {error}"
            write_workflow_state(state_path, state)
            raise
        except UncertainReplyOutcomeError as error:
            entry["last_error"] = str(error)
            state["status"] = STATUS_PENDING_REPLIES
            state["last_error"] = f"reply to comment {entry['comment_id']} outcome unknown: {error}"
            write_workflow_state(state_path, state)
            print(f"  ❓ 回复评论 #{entry['comment_id']} 结果未知（平台可能已接受，恢复时先对账）: {error}")
            continue
        except Exception as error:
            # Pre-write validation/read failures and auth errors provably
            # accepted nothing: the entry stays retryable (uncertain cleared).
            entry["last_error"] = str(error)
            entry["uncertain_outcome"] = False
            state["status"] = STATUS_PENDING_REPLIES
            state["last_error"] = f"reply to comment {entry['comment_id']} failed: {error}"
            write_workflow_state(state_path, state)
            print(f"  ✗ 回复评论 #{entry['comment_id']} 失败: {error}")
            continue

        result = result if isinstance(result, dict) else {}
        entry["status"] = "sent"
        entry["reply_id"] = result.get("note_id") or result.get("id")
        entry["last_error"] = None
        entry["uncertain_outcome"] = False
        state["last_error"] = None
        write_workflow_state(state_path, state)
        print(f"  ✓ 已回复评论 #{entry['comment_id']}")

    completed = all(entry["status"] == "sent" for entry in state["replies"])
    state["status"] = STATUS_SUCCESS if completed else STATUS_PENDING_REPLIES
    if completed:
        state["last_error"] = None
    write_workflow_state(state_path, state)
    _report_uncertain_replies(state)
    return completed


def print_resume_state(state_path: str, state: dict) -> None:
    summary = {
        "state_file": str(Path(state_path).resolve()),
        "status": state["status"],
        "pr_number": state["pr_number"],
        "reply_counts": _reply_counts(state),
    }
    print(f"   RESUME_STATE={json.dumps(summary, ensure_ascii=False, sort_keys=True)}")


def execute_fix_batch(args, api: RepairCli, fixes: list[dict]) -> str:
    """Validate, apply, autosquash, optionally push, and finally reply."""
    default_fixup_target = getattr(args, "fixup_target", None)

    # Complete schema validation happens before Git state checks or file snapshots.
    try:
        for index, fix in enumerate(fixes, 1):
            try:
                validate_fix_fields(fix, default_fixup_target)
            except (TypeError, ValueError) as error:
                raise ValueError(f"fix #{index}: {error}") from error
    except ValueError as error:
        print(f"\n❌ 修复方案校验失败: {error}")
        return STATUS_FAILED

    has_code_fixes = any(fix.get("type", "code_fix") in CODE_FIX_TYPES for fix in fixes)
    context = None
    try:
        if has_code_fixes:
            context = load_pr_git_context(args.work_dir, api, args.pr)
            if getattr(args, "base_branch", None):
                print(
                    "  ℹ️  --base-branch 已忽略; 本次范围校验和 autosquash 固定使用 "
                    f"PR metadata base SHA {context.base_sha[:12]}"
                )
        plans = build_fix_plan(
            fixes,
            args.work_dir,
            context.base_sha if context else None,
            default_fixup_target,
        )
        comment_metadata = validate_pr_comment_ids(
            api,
            args.pr,
            [payload["comment_id"] for plan in plans for payload in planned_reply_payloads(plan)],
        )
        if has_code_fixes and not args.dry_run:
            code_paths = [plan.rel_path for plan in plans if plan.rel_path is not None]
            ensure_no_rebase_in_progress(args.work_dir)
            ensure_clean_index(args.work_dir)
            ensure_clean_worktree(args.work_dir)
            ensure_paths_tracked(args.work_dir, code_paths)
    except (Exception, KeyboardInterrupt) as error:
        print(f"\n❌ 写入前校验失败: {error}")
        return STATUS_FAILED

    reply_specs = build_reply_specs(plans, args.ai_model, comment_metadata)

    if args.dry_run:
        for plan in plans:
            if plan.fix_type == "reply_only":
                print(f"  [Dry Run] 将回复评论 #{plan.payload['comment_id']}")
            else:
                print(
                    f"  [Dry Run] 将处理 {plan.rel_path} 并 fixup 到 "
                    f"{plan.target_sha[:12] if plan.target_sha else 'N/A'}"
                )
        return STATUS_SUCCESS

    try:
        state_path, state = create_workflow_state(args, api, reply_specs, context)
    except Exception as error:
        print(f"\n❌ 无法创建可恢复状态文件: {error}")
        return STATUS_FAILED

    if not has_code_fixes:
        try:
            with handle_termination_signals():
                completed = send_state_replies(api, state_path, state)
        except (Exception, KeyboardInterrupt) as error:
            state["status"] = STATUS_PENDING_REPLIES
            state["last_error"] = str(error)
            write_workflow_state(state_path, state)
            print(f"\n⏸️  回复被中断，可恢复状态已保存: {error}")
            print_resume_state(state_path, state)
            return STATUS_PENDING_REPLIES
        if not completed:
            print("\n⏸️  状态: pending_replies")
            print_resume_state(state_path, state)
            return STATUS_PENDING_REPLIES
        print_resume_state(state_path, state)
        return STATUS_SUCCESS

    code_plans = [plan for plan in plans if plan.fix_type in CODE_FIX_TYPES]
    groups: dict[str, list[PlannedFix]] = {}
    for plan in code_plans:
        if plan.target_sha is None:
            raise RuntimeError("validated code fix unexpectedly has no target SHA")
        groups.setdefault(plan.target_sha, []).append(plan)

    try:
        with (
            handle_termination_signals(),
            FixTransaction(
                args.work_dir,
                context.base_sha,
                code_plans,
                expected_head=context.head_sha,
            ) as transaction,
        ):
            for target_sha, group in groups.items():
                for plan in group:
                    apply_planned_fix(plan, args.work_dir, context.base_sha)
                transaction.commit_group(target_sha, group)
            transaction.autosquash()
            new_head = _resolve_commit(args.work_dir, "HEAD", "rewritten HEAD")
            state["git"]["new_head"] = new_head
            state["status"] = STATUS_PENDING_PUSH
            state["last_error"] = None
            write_workflow_state(state_path, state)
    except RepoStateNotNormalizedError as error:
        state["status"] = STATUS_FAILED
        state["last_error"] = str(error)
        write_workflow_state(state_path, state)
        print(f"\n❌ 修复事务失败且仓库未完全归位: {error}")
        print_resume_state(state_path, state)
        return STATUS_FAILED
    except (Exception, KeyboardInterrupt) as error:
        state["status"] = STATUS_FAILED
        state["last_error"] = str(error)
        write_workflow_state(state_path, state)
        print(f"\n❌ 修复事务失败; 已恢复运行前的 HEAD、index、文件内容和权限: {error}")
        print_resume_state(state_path, state)
        return STATUS_FAILED

    if not getattr(args, "push", False):
        print("\n⏸️  状态: pending_push")
        print("   本地 autosquash 已完成，尚未回复评论。使用状态文件恢复并完成推送/回复:")
        print(f"   python3 review_resolution.py --resume {shlex.quote(state_path)}")
        print_resume_state(state_path, state)
        return STATUS_PENDING_PUSH

    try:
        with handle_termination_signals():
            new_head = push_and_verify(args.work_dir, context)
    except (Exception, KeyboardInterrupt) as error:
        state["status"] = STATUS_PENDING_PUSH
        state["last_error"] = str(error)
        write_workflow_state(state_path, state)
        print("\n⏸️  状态: pending_push")
        print(f"   自动推送未完成或远端状态无法确认，未发送任何回复: {error}")
        print(f"   使用状态文件安全检查远端并恢复: python3 review_resolution.py --resume {shlex.quote(state_path)}")
        print_resume_state(state_path, state)
        return STATUS_PENDING_PUSH

    state["git"]["new_head"] = new_head
    state["git"]["push_status"] = "verified"
    state["status"] = STATUS_PENDING_REPLIES
    state["last_error"] = None
    write_workflow_state(state_path, state)
    print(
        f"\n✅ 已推送并验证 {context.source_push_url} {context.source_ref}: {context.head_sha[:12]} -> {new_head[:12]}"
    )
    try:
        with handle_termination_signals():
            completed = send_state_replies(api, state_path, state)
    except (Exception, KeyboardInterrupt) as error:
        state["status"] = STATUS_PENDING_REPLIES
        state["last_error"] = str(error)
        write_workflow_state(state_path, state)
        print(f"\n⏸️  远端代码已更新，但回复阶段被中断: {error}")
        print_resume_state(state_path, state)
        return STATUS_PENDING_REPLIES
    if not completed:
        print("\n⏸️  远端代码已更新，部分回复仍待发送")
        print_resume_state(state_path, state)
        return STATUS_PENDING_REPLIES
    print_resume_state(state_path, state)
    return STATUS_SUCCESS


def mode_fetch_comments(args, api: RepairCli):
    """模式1: 获取检视意见"""
    print("\n" + "=" * 60)
    print("📥 模式: 获取检视意见")
    print("=" * 60)

    comments = api.get_review_threads(
        args.pr,
        include_self_comments=args.include_self_comments,
        include_bot_comments=args.include_bot_comments,
    )
    # The self filter must not be claimed when the authenticated identity could
    # not be read: surface the unavailability instead of the retired SDK's
    # silent degradation (spec: comment discovery exposes uncertainty).
    filter_status = api.self_filter_status(include_self_comments=args.include_self_comments)
    if filter_status["self_filter"] == "unavailable":
        print(f"\n⚠️  无法读取当前登录用户（{filter_status['reason']}）")
        print("   本轮未能应用 self 评论过滤：输出可能包含当前用户自己的评论，")
        print("   不得据此声称已完成 self 过滤；修复认证后重新抓取可获得过滤结果。")

    if not comments:
        print("\n✅ 没有需要修复的检视意见")
        return

    print(f"\n找到 {len(comments)} 条未解决检视意见")

    # 保存为JSON
    output_dir = Path(args.output_dir)
    output_dir.mkdir(parents=True, exist_ok=True)

    # 从 CLI 目标获取仓库名称
    repo_name = api.repository["repo"].lower().replace("-", "_")
    output_file = output_dir / f"{repo_name}_pr_{args.pr}_unresolved_comments.json"

    output_data = {
        "pr_number": args.pr,
        "fetch_time": datetime.now().isoformat(),
        "metadata": {
            "thread_count": len(comments),
            "include_self_comments": args.include_self_comments,
            "include_bot_comments": args.include_bot_comments,
            "self_filter": filter_status,
            "resolved_state_note": (
                "AtomGit/GitCode review read APIs do not expose a reliable resolved flag. "
                "This file groups all fetched review discussions and filters out "
                "self-authored / bot-only threads by default."
            ),
        },
        "comments": comments,
    }

    with open(output_file, "w", encoding="utf-8") as f:
        json.dump(output_data, f, indent=2, ensure_ascii=False)

    print(f"\n✅ 已保存到: {output_file}")
    print("ℹ️  已自动抓取所有分页评论，并按 discussion_id 聚合线程。")
    print("\n💡 下一步:")
    print("  AI Agent 应该:")
    print("  1. 读取此文件并分析检视意见")
    print("  2. 生成修复方案 (fixes.json)")
    print("  3. ⚠️ 将修复方案以用户可读的格式展示给用户确认")
    print("  4. 用户确认后，运行提交命令")
    print(
        f"\n     python3 review_resolution.py --pr {args.pr} --apply-fixes fixes.json "
        "--push --ai-model <your-model-name>"
    )


def mode_apply_fixes(args, api: RepairCli) -> str:
    """模式2: 应用修复方案，返回 success / failed / pending 状态。"""
    print("\n" + "=" * 60)
    print("🔧 模式: 应用修复方案")
    print("=" * 60)

    # 读取 fixes.json
    with open(args.apply_fixes, encoding="utf-8") as f:
        fixes = json.load(f)

    # 顶层必须是修复对象的数组: dict 会被 len() 计键、逐键迭代产生垃圾结果
    if not isinstance(fixes, list) or not all(isinstance(fx, dict) for fx in fixes):
        print("\n❌ fixes 文件顶层必须是修复对象 (object) 的 JSON 数组")
        return STATUS_FAILED
    if not fixes:
        print("\n❌ fixes 文件为空数组; 没有任何需要应用的修复")
        return STATUS_FAILED

    print(f"\n加载了 {len(fixes)} 个修复方案")
    status = execute_fix_batch(args, api, fixes)

    print("\n" + "=" * 60)
    if status == STATUS_SUCCESS:
        print("✅ 任务完成!")
    elif status == STATUS_PENDING_PUSH:
        print("⏸️  任务等待推送 (pending_push); 未发送修复完成回复")
    elif status == STATUS_PENDING_REPLIES:
        print("⏸️  任务等待恢复回复 (pending_replies); 请使用输出的 --resume 状态文件")
    else:
        print("❌ 任务未完成 (详见上方日志)")
    print("=" * 60)
    print(f"\n🔗 PR 链接: {api.get_pr_url(args.pr)}")
    return status


def validate_resume_context(args, api: RepairCli, state: dict) -> None:
    repository = _state_repository(api)
    if repository != state["repository"]:
        raise ValueError(
            "resume state repository does not match the configured CLI target: "
            f"{state['repository']['owner']}/{state['repository']['repo']} != "
            f"{repository['owner']}/{repository['repo']}"
        )
    if args.pr is not None and args.pr != state["pr_number"]:
        raise ValueError(f"--pr {args.pr} does not match resume state PR #{state['pr_number']}")
    args.pr = state["pr_number"]
    if args.work_dir is not None and str(Path(args.work_dir).resolve()) != state["work_dir"]:
        raise ValueError(
            f"--work-dir resolves to {Path(args.work_dir).resolve()}, but resume state requires {state['work_dir']}"
        )
    args.work_dir = state["work_dir"]


def validate_resume_pr_metadata(api: RepairCli, state: dict) -> None:
    git_state = state.get("git")
    if git_state is None:
        return
    pr = api.get_pr_record(state["pr_number"])
    if not isinstance(pr, dict) or not isinstance(pr.get("head"), dict):
        raise RuntimeError("PR metadata response is missing head data during resume")
    head = pr["head"]
    head_sha = head.get("sha")
    head_branch = head.get("ref")
    head_repo = head.get("repo")
    if not isinstance(head_sha, str) or head_sha.lower() not in {git_state["old_head"], git_state["new_head"]}:
        raise RuntimeError("current PR head is neither the recorded old_head nor new_head")
    if not isinstance(head_branch, str) or f"refs/heads/{head_branch}" != git_state["source_ref"]:
        raise RuntimeError("current PR source ref does not match the resume state")
    if not isinstance(head_repo, dict):
        raise RuntimeError("current PR metadata is missing head.repo")
    push_identity = _normalize_git_repo_url(git_state["push_url"])
    if push_identity not in _repository_identities(head_repo):
        raise RuntimeError("resume state push URL no longer matches the PR source repository")


def mode_resume(args, api: RepairCli) -> str:
    """Resume an atomically checkpointed pending push/reply workflow."""
    print("\n" + "=" * 60)
    print("↻ 模式: 恢复待处理事务")
    print("=" * 60)

    state_path = str(Path(args.resume).resolve())
    state = load_workflow_state(state_path)
    validate_resume_context(args, api, state)
    if state["status"] in {"applying", STATUS_FAILED}:
        raise RuntimeError(
            f"state status {state['status']} is not resumable; no irreversible push/reply checkpoint is pending"
        )

    try:
        with handle_termination_signals():
            reconcile_state_replies(api, state_path, state)
            pending_comment_ids = [entry["comment_id"] for entry in state["replies"] if entry["status"] == "pending"]
            if pending_comment_ids:
                validate_pr_comment_ids(api, state["pr_number"], pending_comment_ids)
            validate_resume_pr_metadata(api, state)
            resume_push(state_path, state)
            completed = send_state_replies(api, state_path, state)
    except (Exception, KeyboardInterrupt) as error:
        if state.get("git") and state["git"].get("push_status") != "verified":
            state["status"] = STATUS_PENDING_PUSH
        else:
            state["status"] = STATUS_PENDING_REPLIES
        state["last_error"] = str(error)
        write_workflow_state(state_path, state)
        print(f"\n⏸️  恢复未完成: {error}")
        _report_uncertain_replies(state)
        print_resume_state(state_path, state)
        return state["status"]

    if not completed:
        print("\n⏸️  部分回复仍待发送")
        print_resume_state(state_path, state)
        return STATUS_PENDING_REPLIES
    print("\n✅ 推送已验证，所有回复均已完成")
    print_resume_state(state_path, state)
    return STATUS_SUCCESS


def _load_reply_body(args) -> str:
    if args.reply_file:
        with open(args.reply_file, encoding="utf-8") as f:
            return f.read()
    if args.reply_body:
        return args.reply_body
    raise ValueError("回复单条评论需要指定 --reply-body 或 --reply-file")


def mode_reply_comment(args, api: RepairCli):
    """Reply to one specific PR review comment."""
    print("\n" + "=" * 60)
    print("💬 模式: 回复单条检视意见")
    print("=" * 60)

    reply_body = add_ai_signature(_load_reply_body(args), args.ai_model)
    validate_pr_comment_ids(api, args.pr, [args.reply_comment])
    if args.dry_run:
        print(f"\n[Dry Run] 将回复评论 #{args.reply_comment}:\n{reply_body}")
        return

    result = api.reply_to_comment(args.pr, args.reply_comment, reply_body, reply_mode=args.reply_mode)
    print(f"\n✅ 已回复评论 #{args.reply_comment}")
    print(f"🔗 PR 链接: {api.get_pr_url(args.pr)}")
    reply_id = result.get("note_id") or result.get("id")
    if reply_id:
        print(f"💬 回复 ID: {reply_id}")
    if result.get("reply_mode"):
        print(f"📝 回复模式: {result['reply_mode']}")
    if result.get("thread_url"):
        print(f"🧵 线程链接: {result['thread_url']}")
    if result.get("visibility_hint"):
        print(f"ℹ️  可见性提示: {result['visibility_hint']}")


def _parse_resolved(value: str) -> bool:
    return value.lower() in {"1", "true", "yes", "y", "resolved"}


def mode_resolve_comment(args, api: RepairCli):
    """Resolve or reopen one review comment discussion."""
    print("\n" + "=" * 60)
    print("✅ 模式: 修改检视意见解决状态")
    print("=" * 60)

    resolved = _parse_resolved(args.resolved)
    if args.dry_run:
        target = (
            f"discussion {args.resolve_discussion}" if args.resolve_discussion else f"comment {args.resolve_comment}"
        )
        print(f"\n[Dry Run] 将设置 {target} resolved={resolved}")
        return

    if args.resolve_discussion:
        api.resolve_discussion(args.pr, args.resolve_discussion, resolved)
        print(f"\n✅ 已更新 discussion {args.resolve_discussion}: resolved={resolved}")
    else:
        validate_pr_comment_ids(api, args.pr, [args.resolve_comment])
        api.resolve_comment(args.pr, args.resolve_comment, resolved)
        print(f"\n✅ 已更新评论 #{args.resolve_comment}: resolved={resolved}")
    print(f"🔗 PR 链接: {api.get_pr_url(args.pr)}")


