    try:
        cli = atomgit_cli.resolve_cli()
        atomgit_cli.check_cli_identity(cli)
        target = atomgit_cli.resolve_target(
            owner=args.owner,
            repo=args.repo,
            url=args.url,
            config_path=args.config or "config.json",
            explicit_config=args.config is not None,
            remotes=atomgit_cli.read_git_remotes(),
        )
    except (atomgit_cli.CLIError, atomgit_cli.TargetResolutionError) as e:
        print(f"\n❌ 初始化失败: {e}")
        sys.exit(1)

    if args.pr is None and not args.resume:
        args.pr = (target.url_info or {}).get("pr_number")
    if args.pr is None and not args.resume:
        print("\n❌ 缺少 PR 编号。请通过 --pr 指定，或传入包含 PR 编号的 --url。")
        sys.exit(1)

    repair_service = RepairCli(cli, target)

    if args.pr is not None:
        print(f"\n📋 PR: #{args.pr}")
    else:
        print(f"\n📋 恢复状态: {Path(args.resume).resolve()}")
    print(f"🏠 仓库: {target.slug}")
    if args.url:
        print(f"🔗 链接: {args.url}")
    print(f"🤖 AI模型: {args.ai_model}")

    if args.dry_run:
        print("⚠️  Dry Run 模式（仅显示计划）")

    # 根据模式执行
    if args.fetch_comments:
        try:
            mode_fetch_comments(args, repair_service)
        except Exception as e:
            print(f"\n❌ 获取检视意见失败: {e}")
            sys.exit(1)
    elif args.apply_fixes:
        status = mode_apply_fixes(args, repair_service)
        if status == STATUS_FAILED:
            sys.exit(1)
        if status in {STATUS_PENDING_PUSH, STATUS_PENDING_REPLIES}:
            sys.exit(2)
    elif args.resume:
        try:
            status = mode_resume(args, repair_service)
        except Exception as e:
            print(f"\n❌ 恢复失败: {e}")
            sys.exit(1)
        if status == STATUS_FAILED:
            sys.exit(1)
        if status in {STATUS_PENDING_PUSH, STATUS_PENDING_REPLIES}:
            sys.exit(2)
    elif args.reply_comment:
        try:
            mode_reply_comment(args, repair_service)
        except Exception as e:
            print(f"\n❌ 回复失败: {e}")
            sys.exit(1)
    elif args.resolve_comment or args.resolve_discussion:
        try:
            mode_resolve_comment(args, repair_service)
        except Exception as e:
            print(f"\n❌ 更新解决状态失败: {e}")
            sys.exit(1)


